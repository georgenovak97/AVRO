def set_language(lang):
    global _CURRENT
    try:
        if lang is None:
            lang = u""
        if not isinstance(lang, unicode):
            lang = unicode(lang)
    except Exception:
        lang = u""
    lang = lang.strip().lower()
    if lang not in _LANGUAGES:
        lang = u"en"
    _CURRENT = lang


def get_language():
    return _CURRENT


def t(key, lang=None, **kwargs):
    """Translate key; optional ``lang`` override for ribbon metadata."""
    lng = lang or _CURRENT
    table = _STRINGS.get(lng, _STRINGS[u"ru"])
    text = table.get(key, _STRINGS[u"ru"].get(key, key))
    if kwargs:
        return text.format(**kwargs)
    return text


def init_from_config():
    """Load language from current Revit UI (use after every Reload / Update)."""
    try:
        import config
        set_language(config.read_ui_language())
    except Exception as ex:
        try:
            import config as _cfg
            _cfg._log(u"i18n.init_from_config: {}".format(_cfg._u(ex)))
        except Exception:
            pass
        set_language(u"en")
